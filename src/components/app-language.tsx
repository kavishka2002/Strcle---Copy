function translateText(value: string, language: AppLanguage): string {
  if (language === "en") return en[value] ?? value;
  const trimmed = value.trim();
  const translated = si[trimmed];
  if (translated) return value.replace(trimmed, translated);
  for (const [pattern, format] of sinhalaPatterns) {
    const match = trimmed.match(pattern);
    if (match) return value.replace(trimmed, format(match));
  }
  return value;
}

export function translateUiText(value: string, language: AppLanguage): string {
  return translateText(value, language);
}

function localizedNode(node: ReactNode, language: AppLanguage): ReactNode {
  if (typeof node === "string") return translateText(node, language);
  if (typeof node === "number" || node === null || node === undefined || typeof node === "boolean") return node;
  if (Array.isArray(node)) return Children.map(node, child => localizedNode(child, language));
  if (!isValidElement(node)) return node;

  const element = node as React.ReactElement<Record<string, unknown>>;
  const className = typeof element.props.className === "string" ? element.props.className : "";
  if (/(?:^|\s)(?:print-only|print-sheet|print-sticker|custom-print-page|sticker-canvas|preview-sticker|cv-print-root)(?:\s|$)/.test(className)) return node;
  const props: Record<string, unknown> = { ...element.props };
  for (const attribute of ["placeholder", "title", "aria-label", "aria-description"]) {
    const value = props[attribute];
    if (typeof value === "string") props[attribute] = translateText(value, language);
  }
  const children = "children" in props ? localizedNode(props.children as ReactNode, language) : undefined;
  return cloneElement(element, props, children);
}

const LanguageContext = createContext<{
  language: AppLanguage;
  theme: AppTheme;
  toggle: () => void;
  toggleTheme: () => void;
  setScope: (scope: string) => void;
}>({
  language: "si",
  theme: "light",
  toggle: () => undefined,
  toggleTheme: () => undefined,
  setScope: () => undefined
});

export function AppLanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<AppLanguage>("si");
  const [theme, setTheme] = useState<AppTheme>("light");
  const [scope, setScope] = useState("global");
  useEffect(() => {
    try {
      const scoped = localStorage.getItem(`${LANGUAGE_KEY}:${scope}`);
      const stored = scoped ?? (scope === "global" ? localStorage.getItem(LANGUAGE_KEY) : "si");
      window.setTimeout(() => setLanguage(stored === "en" ? "en" : "si"), 0);
    } catch (error) {
      console.error("Could not read the saved application language.", error);
    }
  }, [scope]);

  useEffect(() => {
    try {
      const stored = localStorage.getItem(`${THEME_KEY}:${scope}`) ??
        (scope === "global" ? null : localStorage.getItem(`${THEME_KEY}:global`));
      window.setTimeout(() => setTheme(stored === "dark" ? "dark" : "light"), 0);
    } catch (error) {
      console.error("Could not read the saved application theme.", error);
    }
  }, [scope]);

  useEffect(() => {
    document.documentElement.dataset.theme = theme;
  }, [theme]);

  const value = useMemo(() => ({
    language,
    theme,
    setScope,
    toggleTheme: () => {
      const next = theme === "dark" ? "light" : "dark";
      try {
        localStorage.setItem(`${THEME_KEY}:${scope}`, next);
        setTheme(next);
      } catch (error) {
        console.error("Could not save the application theme.", error);
        setTheme(next);
      }
    },
    toggle: () => {
      const next = language === "si" ? "en" : "si";
      try {
        localStorage.setItem(`${LANGUAGE_KEY}:${scope}`, next);
        if (scope === "global") localStorage.setItem(LANGUAGE_KEY, next);
        setLanguage(next);
      } catch (error) {
        console.error("Could not save the application language.", error);
        setLanguage(next);
      }
    }
  }), [language, scope, theme]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useAppLanguage() {
  return useContext(LanguageContext);
}

export function LanguageToggle() {
  const { language, toggle } = useAppLanguage();
  return <button type="button" className="language-toggle" data-trial-allow aria-label={language === "si" ? "Switch to English" : "සිංහලට මාරු වන්න"} onClick={toggle}>
    <span>සි</span>
    <span>{language === "si" ? "සිංහල" : "English"}</span>
  </button>;
}

export function ThemeToggle() {
  const { language, theme, toggleTheme } = useAppLanguage();
  const nextMode = theme === "dark"
    ? (language === "si" ? "ආලෝක තේමාවට මාරු වන්න" : "Switch to light mode")
    : (language === "si" ? "අඳුරු තේමාවට මාරු වන්න" : "Switch to dark mode");
  return <button type="button" className="theme-toggle" data-trial-allow aria-label={nextMode} title={nextMode} onClick={toggleTheme}>
    {theme === "dark" ? <Sun size={16}/> : <Moon size={16}/>}
    <span>{theme === "dark" ? (language === "si" ? "අඳුරු" : "Dark") : (language === "si" ? "ආලෝක" : "Light")}</span>
  </button>;
}

export function LocalizedUi({ children }: { children: ReactNode }) {
  const { language } = useAppLanguage();
  return <>{Children.map(children, child => localizedNode(child, language))}</>;
}
